    const exports = instance.exports;
    // ... (wasm-bindgen generated)
}
EOF

echo "  Inline JS: $PKG_DIR/falcon_wasm_inline.js"
echo ""
echo "✓ Done. Files in $PKG_DIR:"
ls -lh "$PKG_DIR" | grep -v '\.tmp$'
